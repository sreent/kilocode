import type brand from "./brand.json"

type Brand = typeof brand

export type Rule =
  | { name: string; files: string[]; apply: (text: string, file: string) => string }
  | { name: string; assets: Record<string, string> }
  | { name: string; generated: Record<string, string> }

const banner = "Generated by brand/apply.ts from brand/brand.json: edit that file and run `bun brand/apply.ts`."

// Kilo's own services keep their names wherever they are still mentioned: "Kilo Gateway" is Kilo's
// gateway, not ours. So does Kilo v5, the legacy extension whose settings can be migrated.
const services = "Gateway|Pass|Cloud|Marketplace|Auto|credits?|account|accounts|Remote|Org|v5"

// The CLI's subcommands, which follow the command's name in text such as "run `kilo serve`".
const subcommands =
  "serve|run|auth|upgrade|uninstall|org|mcp|models|debug|agent|export|import|stats|session|pr|daemon|attach|plugin|db|acp|providers|config|worktree|help|completion|generate|console|roll-call"

/** The product's name in text people read: "Kilo Code" and "Kilo" become the brand's name. */
export function product(text: string, b: Brand) {
  return text
    .replace(/\bKilo Code\b/g, b.name)
    .replace(new RegExp(`\\bKilo\\b(?![ -](?:${services}|hosted)\\b)`, "g"), b.name)
    .replace(/`kilo(?=\s)/g, "`" + b.command)
    .replace(new RegExp(`\\bkilo (${subcommands})\\b`, "g"), `${b.command} $1`)
    .replace(/\bkilo (?=--?[a-z])/g, `${b.command} `)
    .replace(/~\/\.config\/kilo\//g, `~/.config/${b.command}/`)
}

/**
 * Text the agent reads about itself: the product's name, and tucode's links and paths instead of
 * Kilo's. Kilo's documentation pages are in this repository too, under packages/kilo-docs/pages.
 */
export function prompt(text: string, b: Brand) {
  const docs = `${b.repository}/blob/main/packages/kilo-docs/pages`
  return product(
    text
      .replaceAll("https://github.com/Kilo-Org/kilocode", b.repository)
      .replace(/https:\/\/kilo\.ai\/docs\/([\w/-]+)/g, `${docs}/$1.md`)
      .replace(/https:\/\/kilo\.ai\/docs\b/g, docs.replace("/blob/", "/tree/"))
      .replaceAll("/etc/kilo/", `/etc/${b.managed.dir}/`)
      .replaceAll("/Library/Application Support/kilo/", `/Library/Application Support/${b.managed.dir}/`)
      .replaceAll("%ProgramData%\\kilo\\", `%ProgramData%\\${b.managed.dir}\\`),
    b,
  )
}

/**
 * How the tree spells the brand's values once it carries them, in a fixed order so that apply.ts
 * can pair an old spelling with the new one when brand.json changes. Besides the values the rules
 * write, these are the spellings code derives from the name (a User-Agent drops its spaces) and
 * Markdown links to a heading that is the name.
 */
export function spellings(b: Brand) {
  return [
    b.name,
    b.name.replaceAll(" ", ""),
    b.name.replaceAll(" ", "-"),
    `#${b.name.toLowerCase().replaceAll(" ", "-")}`,
    b.vscode.displayName,
    b.jetbrains.name,
    b.jetbrains.vendor,
    `${b.vscode.publisher}.${b.vscode.name}`,
    JSON.stringify(b.vscode.name),
    b.repository,
    b.image,
    b.npm.cli,
    `${b.npm.scope}/`,
    b.jetbrains.id,
    b.managed.macDomain,
  ]
}

/** Applies `transform` to the values of double-quoted string literals, never to object keys. */
export function values(text: string, transform: (value: string) => string) {
  return text.replace(/"((?:[^"\\\n]|\\.)*)"(\s*:)?/g, (match, value: string, key: string | undefined) =>
    key ? match : `"${transform(value)}"`,
  )
}

/** Applies `transform` to the values of a .properties file, never to keys or comments. */
export function properties(text: string, transform: (value: string) => string) {
  let continued = false
  return text
    .split("\n")
    .map((line) => {
      const value = continued ? line : undefined
      continued = /(^|[^\\])(\\\\)*\\$/.test(line)
      if (value !== undefined) return transform(value)
      if (/^\s*[#!]/.test(line)) return line
      const at = line.search(/(?<!\\)[=:]/)
      return at < 0 ? line : line.slice(0, at + 1) + transform(line.slice(at + 1))
    })
    .join("\n")
}

