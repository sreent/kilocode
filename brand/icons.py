#!/usr/bin/env python3
# Draws tucode's logo and icons and writes them under brand/: logo.svg, mark.svg and, in icons/,
# the sizes the IDEs and the admin console use, their PNGs, favicon.ico, the VS Code icon font and
# svg.ts, the markup for pages that draw the logo inline. Run it again after changing the letters,
# then `bun brand/apply.ts` copies the icons into the packages. Needs Pillow, fontTools and brotli:
#
#   pip install pillow fonttools brotli
#   python3 brand/icons.py
#
# The mark is four pixel letters, "tu" over a prompt, ">_". They sit on a grid of 11.5 units across
# the logo's 512-pixel square: 2-unit margins, letters 3.25 units square and 1 unit apart, 1-unit
# strokes, and corners cut 0.68 units.

import os

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from PIL import Image, ImageDraw

root = os.path.dirname(os.path.abspath(__file__))
navy = "#13294B"
unit = 512 / 11.5
cut = 0.68

# Each letter's outlines, in units from its top left corner: its edge first, then any holes.
letters = {
    "t": [
        [
            (0.75, 0),
            (1.75, 0),
            (1.75, 0.875),
            (3, 0.875),
            (3, 1.875),
            (1.75, 1.875),
            (1.75, 2.25),
            (3, 2.25),
            (3, 3.25),
            (0.75 + cut, 3.25),
            (0.75, 3.25 - cut),
            (0.75, 1.875),
            (0, 1.875),
            (0, 0.875),
            (0.75, 0.875),
        ]
    ],
    "u": [
        [
            (0, 0),
            (1, 0),
            (1, 2.25),
            (2.25, 2.25),
            (2.25, 0),
            (3.25, 0),
            (3.25, 3.25 - cut),
            (3.25 - cut, 3.25),
            (cut, 3.25),
            (0, 3.25 - cut),
        ]
    ],
    ">": [[(0, 0), (1, 0), (2.25, 1.125), (2.25, 2.125), (1, 3.25), (0, 3.25), (0, 2.6), (1.5, 1.625), (0, 0.65)]],
    "_": [[(0, 2.25), (3.25, 2.25), (3.25, 3.25), (0, 3.25)]],
}
rows = ["tu", ">_"]


def outlines():
    """The mark's outlines in logo pixels, each with whether it's a hole."""
    for r, row in enumerate(rows):
        for c, letter in enumerate(row):
            x0, y0 = 2 + 4.25 * c, 2 + 4.25 * r
            for i, points in enumerate(letters[letter]):
                yield [((x0 + x) * unit, (y0 + y) * unit) for x, y in points], i > 0


def num(value):
    return f"{value:.2f}".rstrip("0").rstrip(".")


path = "".join("M" + "L".join(f"{num(x)} {num(y)}" for x, y in points) + "Z" for points, _ in outlines())
# The mark alone, half a unit around the letters.
view = (1.5 * unit, 1.5 * unit, 8.5 * unit)
box = " ".join(num(v) for v in (view[0], view[1], view[2], view[2]))
square = '<path d="M512 0H0V512H512V0Z" fill="' + navy + '"/>'


def write(name, content):
    mode = "wb" if isinstance(content, bytes) else "w"
    with open(os.path.join(root, name), mode) as file:
        file.write(content)


def logo(size):
    return "\n".join(
        [
            f'<svg width="{size}" height="{size}" viewBox="0 0 512 512" fill="none" xmlns="http://www.w3.org/2000/svg">',
            square,
            f'<path d="{path}" fill="white" fill-rule="evenodd"/>',
            "</svg>",
            "",
        ]
    )


def mark(size, color):
    return "\n".join(
        [
            f'<svg width="{size}" height="{size}" viewBox="{box}" fill="none" xmlns="http://www.w3.org/2000/svg">',
            f'<path d="{path}" fill="{color}" fill-rule="evenodd"/>',
            "</svg>",
            "",
        ]
    )


write("logo.svg", logo(512))
write("mark.svg", mark(24, "currentColor"))
write("icons/logo-40.svg", logo(40))
write("icons/logo-64.svg", logo(64))
# JetBrains' icon colors for light and dark themes.
write("icons/mark-16.svg", mark(16, "#6C707E"))
write("icons/mark-16_dark.svg", mark(16, "#CED0D6"))
write("icons/mark-20.svg", mark(20, "#6C707E"))
write("icons/mark-20_dark.svg", mark(20, "#CED0D6"))
write("icons/mark-black.svg", mark(256, "#000000"))
write("icons/mark-white.svg", mark(256, "#FFFFFF"))
write(
    "icons/svg.ts",
    "\n".join(
        [
            "// Generated by brand/icons.py: change the letters there and run it again.",
            "// The logo and the mark as SVG markup, for pages that draw them inline.",
            "export const logo = {",
            '  viewBox: "0 0 512 512",',
            f'  body: `{square}<path d="{path}" fill="white" fill-rule="evenodd"/>`,',
            "}",
            "",
            "export const mark = {",
            f'  viewBox: "{box}",',
            f'  body: `<path d="{path}" fill="currentColor" fill-rule="evenodd"/>`,',
            "}",
            "",
        ]
    ),
)


def coverage(size, x0, y0, side):
    """How much of each pixel the letters cover, when the image shows that square of the logo."""
    over = 8
    k = size * over / side
    mask = Image.new("L", (size * over, size * over), 0)
    draw = ImageDraw.Draw(mask)
    for points, hole in outlines():
        draw.polygon([((x - x0) * k, (y - y0) * k) for x, y in points], fill=0 if hole else 255)
    return mask.reduce(over)


def tile(size):
    mask = coverage(size, 0, 0, 512)
    return Image.composite(Image.new("RGB", mask.size, "white"), Image.new("RGB", mask.size, navy), mask)


def glyphs(size, color):
    mask = coverage(size, *view)
    image = Image.new("RGBA", mask.size, color)
    image.putalpha(mask)
    return image


tile(512).save(os.path.join(root, "icons/logo-512.png"), optimize=True)
glyphs(256, "black").save(os.path.join(root, "icons/mark-black-256.png"), optimize=True)
glyphs(256, "white").save(os.path.join(root, "icons/mark-white-256.png"), optimize=True)
favicons = [tile(size) for size in (16, 32, 48)]
favicons[-1].save(
    os.path.join(root, "icons/favicon.ico"),
    sizes=[image.size for image in favicons],
    append_images=favicons[:-1],
)

# The VS Code icon font, whose one glyph (U+F101) is the mark: status bar text shows it as
# $(kilo-logo). It fits the letters into the em the way Kilo's font did: 1000 units, 850 above the
# baseline.
em, ascent, descent, margin = 1000, 850, -150, 80
side = 7.5 * unit
scale = (em - 2 * margin) / (side * 1.25)
left = (em - side * scale) / 2
top = (ascent + descent) / 2 + side * scale / 2 + 40

pen = TTGlyphPen(None)
for points, hole in outlines():
    contour = [(round(left + (x - 2 * unit) * scale), round(top - (y - 2 * unit) * scale)) for x, y in points]
    area = sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(contour, contour[1:] + contour[:1]))
    # TrueType fills an outline drawn clockwise and leaves a hole drawn counterclockwise.
    if (area > 0) != hole:
        contour.reverse()
    pen.moveTo(contour[0])
    for point in contour[1:]:
        pen.lineTo(point)
    pen.closePath()
glyph = pen.glyph()

fb = FontBuilder(em, isTTF=True)
fb.setupGlyphOrder([".notdef", "kilo-logo"])
fb.setupCharacterMap({0xF101: "kilo-logo"})
fb.setupGlyf({".notdef": TTGlyphPen(None).glyph(), "kilo-logo": glyph})
glyph.recalcBounds(fb.font["glyf"])
fb.setupHorizontalMetrics({".notdef": (500, 0), "kilo-logo": (em, glyph.xMin)})
fb.setupHorizontalHeader(ascent=ascent, descent=descent)
fb.setupNameTable({"familyName": "brand-icon-font", "styleName": "Regular"})
fb.setupOS2(sTypoAscender=ascent, sTypoDescender=descent, usWinAscent=ascent, usWinDescent=-descent)
fb.setupPost()
fb.font.flavor = "woff2"
fb.save(os.path.join(root, "icons/icon-font.woff2"))
print("wrote brand/logo.svg, brand/mark.svg and brand/icons")
